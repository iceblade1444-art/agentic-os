const normalize = (value) => SUPPORTED_LOCALES.some(([code]) => code === value) ? value : "ru-RU";
let currentLocale = (() => {
  try {
    const stored = typeof localStorage !== "undefined" ? localStorage.getItem("aos_ui_locale") : "";
    if (stored) return normalize(stored);
  } catch { /* storage unavailable */ }
  const browser = typeof navigator !== "undefined" ? navigator.language || "" : "";
  return browser.startsWith("uz") ? "uz-UZ" : browser.startsWith("en") ? "en-US" : "ru-RU";
})();

export function setLocale(locale, persist = true) {
  currentLocale = normalize(locale);
  if (typeof document !== "undefined") document.documentElement.lang = currentLocale.slice(0, 2);
  if (persist) {
    try {
      if (typeof localStorage !== "undefined") localStorage.setItem("aos_ui_locale", currentLocale);
    } catch { /* storage unavailable */ }
  }
  return currentLocale;
}

export function getLocale() {
  return currentLocale;
}

export function t(key, values = {}) {
  const template = COPY[currentLocale]?.[key] || COPY["en-US"]?.[key] || key;
  return Object.entries(values).reduce(
    (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
    template,
  );
}

export function localizedDate(value, options = { day: "numeric", month: "short" }) {
  const date = value instanceof Date ? value : new Date(value);
  return Number.isNaN(date.valueOf()) ? "" : new Intl.DateTimeFormat(currentLocale, options).format(date);
}
